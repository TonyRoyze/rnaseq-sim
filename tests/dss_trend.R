source('scripts/custom_simulation/method_settings.R')
suppressPackageStartupMessages(library(DSS))
original <- get('est.trend', asNamespace('DSS'))
set.seed(42)
# Two expression bands leave empty bins between them, despite valid counts.
mu <- c(exp(seq(1.2, 3, length.out=500)), exp(seq(5, 7, length.out=500)))
counts <- matrix(rnbinom(length(mu)*20, mu=mu, size=10), ncol=20)
rownames(counts) <- paste0('gene', seq_along(mu))
colnames(counts) <- paste0('sample', 1:20)
groups <- rep(0:1, each=10)
seq_data <- DSS::newSeqCountSet(counts, data.frame(designs=groups, row.names=colnames(counts)))
seq_data <- DSS::estNormFactors(seq_data)
set.seed(1)
failed <- try(DSS::estDispersion(seq_data, trend=TRUE), silent=TRUE)
stopifnot(inherits(failed, 'try-error'), grepl('missing values not allowed', failed))
set.seed(1)
fixed <- dss_est_dispersion(seq_data, trend=TRUE)
stopifnot(all(is.finite(DSS::dispersion(fixed))))
result <- DSS::waldTest(fixed, 1, 0)
stopifnot(nrow(result)==nrow(counts), all(is.finite(result$pval)))
stopifnot(identical(original, get('est.trend', asNamespace('DSS'))))
set.seed(2)
a <- DSS::estDispersion(seq_data, trend=FALSE)
set.seed(2)
b <- dss_est_dispersion(seq_data, trend=FALSE)
stopifnot(identical(DSS::dispersion(a), DSS::dispersion(b)))
cat('PASS: reproduced empty-bin failure, repaired trend and Wald test, unchanged namespace and default dispersion\n')
